const express = require('express')
const request = require('supertest')
const { createWowRouter } = require('aduoer-wow-sdk')
const { createInterleavedSearch } = require('../../../dist/qqMergedSearch')
const { createAdapter, createWowContextResolver } = require('../../../dist/adapter')
const { QQClient } = require('../../../dist/clients/QQClient')
const { NeteaseClient } = require('../../../dist/clients/NeteaseClient')

const account = () => ({ platform: 'qq', cookie: '', name: 'QQ', apiAccessKey: 'key', stateless: true, useLuoxue: true, lxSource: [] })
const items = (prefix, count) => Array.from({ length: count }, (_, index) => ({ id: `${prefix}${index + 1}`, title: '同一歌曲' }))
const fetchItems = rows => jest.fn(async (_keyword, offset, limit) => ({ items: rows.slice(offset, offset + limit), offset, limit, hasMore: offset + limit < rows.length }))
const tag = item => ({ ...item, id: `netease:${item.id}` })
const song = id => ({ id, title: '兔子洞', artists: [{ id: '27', name: 'DECO*27' }], album: { id: '12', name: '专辑', coverUrl: '' }, durationMs: 180000, favorite: false, qualities: [], aliases: [], mvId: null, fee: false })

afterEach(() => { jest.restoreAllMocks(); delete global.__musicPlatformFactory__ })

test('按 QQ1 wy1 QQ2 wy2 排列，同名歌曲保留两个版本', async () => {
  const qq = fetchItems(items('q', 3))
  const wy = fetchItems(items('', 3))
  const search = createInterleavedSearch(account(), 'tracks', qq, wy, tag)
  const result = await search('兔子洞', 0, 6)
  expect(result.items.map(item => item.id)).toEqual(['q1', 'netease:1', 'q2', 'netease:2', 'q3', 'netease:3'])
  expect(result.hasMore).toBe(false)
  expect(qq).toHaveBeenCalledTimes(1)
  expect(wy).toHaveBeenCalledTimes(1)
})

test('奇数 offset、并发分页和跨上游批次保持同一条顺序', async () => {
  const qq = fetchItems(items('q', 40)), wy = fetchItems(items('', 40))
  const search = createInterleavedSearch(account(), 'tracks', qq, wy, tag)
  const [first, second, boundary] = await Promise.all([search('k', 0, 5), search('k', 5, 5), search('k', 59, 4)])
  expect(first.items.map(item => item.id)).toEqual(['q1', 'netease:1', 'q2', 'netease:2', 'q3'])
  expect(second.items.map(item => item.id)).toEqual(['netease:3', 'q4', 'netease:4', 'q5', 'netease:5'])
  expect(boundary.items.map(item => item.id)).toEqual(['netease:30', 'q31', 'netease:31', 'q32'])
  expect(boundary.hasMore).toBe(true)
  expect(qq.mock.calls.map(call => call[1])).toEqual([0, 30])
  expect(wy.mock.calls.map(call => call[1])).toEqual([0, 30])
})

test('一边耗尽后按另一边原顺序接续，翻页保留尾部所有结果', async () => {
  const search = createInterleavedSearch(account(), 'tracks', fetchItems(items('q', 2)), fetchItems(items('', 65)), tag)
  expect((await search('k', 0, 7)).items.map(item => item.id)).toEqual(['q1', 'netease:1', 'q2', 'netease:2', 'netease:3', 'netease:4', 'netease:5'])
  const last = await search('k', 63, 10)
  expect(last.items.map(item => item.id)).toEqual(['netease:62', 'netease:63', 'netease:64', 'netease:65'])
  expect(last.hasMore).toBe(false)
})

test('单个平台失败仍返回另一平台结果，双边失败返回 502 且允许重试', async () => {
  jest.spyOn(console, 'warn').mockImplementation(() => {})
  const failed = jest.fn().mockRejectedValue(new Error('upstream down'))
  const search = createInterleavedSearch(account(), 'tracks', failed, fetchItems(items('', 2)), tag)
  expect((await search('k', 0, 20)).items.map(item => item.id)).toEqual(['netease:1', 'netease:2'])
  const recovering = jest.fn().mockRejectedValueOnce(new Error('temporary')).mockResolvedValue({ items: items('q', 1), hasMore: false })
  const retry = createInterleavedSearch(account(), 'tracks', recovering, failed, tag)
  await expect(retry('k', 0, 20)).rejects.toMatchObject({ status: 502 })
  expect((await retry('k', 0, 20)).items.map(item => item.id)).toEqual(['q1'])
})

test('网易详情、歌词、嵌套 ID 和洛雪 wy 播放通过 QQ 的 SDK 入口正确路由', async () => {
  const session = account()
  jest.spyOn(QQClient.prototype, 'searchTracks').mockResolvedValue({ items: [song('qq-mid')], hasMore: false })
  jest.spyOn(NeteaseClient.prototype, 'searchTracks').mockResolvedValue({ items: [song('123')], hasMore: false })
  const detail = jest.spyOn(NeteaseClient.prototype, 'getTrackDetail').mockResolvedValue(song('123'))
  const lyrics = jest.spyOn(NeteaseClient.prototype, 'getTrackLyrics').mockResolvedValue({ lyrics: '[00:00.00]歌词', wordLyrics: '', translatedLyrics: '' })
  const official = jest.spyOn(NeteaseClient.prototype, 'getTrackUrlForQuality')
  const audio = { url: 'https://lx.test/wy.flac', quality: 'lossless', format: '', bitrate: null, size: 0 }
  const lx = { resolveTrackUrl: jest.fn().mockResolvedValue(audio) }
  const registry = { sessions: [session], byAccessKey: new Map([['key', session]]) }
  const app = express().use(createWowRouter({ resolveContext: createWowContextResolver(registry, lx), validateResponses: true }))
  const search = await request(app).get('/v1/search/tracks?keyword=兔子洞&limit=2').set('Authorization', 'key').expect(200)
  expect(search.body.data.items.map(item => item.id)).toEqual(['qq-mid', 'netease:123'])
  expect(search.body.data.items[1].artists[0].id).toBe('netease:27')
  expect(search.body.data.items[1].album.id).toBe('netease:12')
  const track = await request(app).get('/v1/track?id=netease:123').set('Authorization', 'key').expect(200)
  expect(track.body.data.id).toBe('netease:123')
  expect(detail).toHaveBeenCalledWith('123')
  await request(app).get('/v1/track/lyrics?id=netease:123').set('Authorization', 'key').expect(200)
  expect(lyrics).toHaveBeenCalledWith('123')
  const result = await request(app).get('/v1/track/url?id=netease:123&quality=lossless').set('Authorization', 'key').expect(200)
  expect(result.body.data).toEqual(audio)
  expect(lx.resolveTrackUrl).toHaveBeenCalledWith('netease', '123', 'lossless', [], { allowFallback: true, musicInfo: expect.objectContaining({ source: 'wy', songId: 123, name: '兔子洞', singer: 'DECO*27' }) })
  expect(official).not.toHaveBeenCalled()
  lx.resolveTrackUrl.mockResolvedValue(undefined)
  await request(app).get('/v1/track/url?id=netease:123&quality=lossless').set('Authorization', 'key').expect(422)
  await request(app).get('/v1/track?id=netease:invalid').set('Authorization', 'key').expect(400)
  expect(official).not.toHaveBeenCalled()
})

test.each(['Artists', 'Albums', 'Playlists'])('搜索 %s 交替合并并将网易 ID 路由到对应详情', async kind => {
  jest.spyOn(QQClient.prototype, `search${kind}`).mockResolvedValue({ items: [{ id: 'qq', name: 'QQ' }], hasMore: false })
  jest.spyOn(NeteaseClient.prototype, `search${kind}`).mockResolvedValue({ items: [{ id: '123', name: '网易' }], hasMore: false })
  const detailMethod = { Artists: 'getArtistDetail', Albums: 'getAlbumDetail', Playlists: 'getPlaylistDetail' }[kind]
  const detail = jest.spyOn(NeteaseClient.prototype, detailMethod).mockResolvedValue({ id: '123', name: '网易', tracks: [song('456')] })
  const adapter = createAdapter(account())
  expect((await adapter[`search${kind}`]('k', 0, 2)).items.map(item => item.id)).toEqual(['qq', 'netease:123'])
  const result = await adapter[detailMethod]('netease:123', 1)
  expect(detail).toHaveBeenCalledWith('123', 1)
  expect(result.id).toBe('netease:123')
  expect(result.tracks[0].id).toBe('netease:456')
})

